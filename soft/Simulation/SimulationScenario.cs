    internal static SimulationScenario Find(string id) =>
        All.First(scenario => string.Equals(scenario.Id, id, StringComparison.Ordinal));

    private static SimulationStep Frame(
        string time,
        string title,
        string description,
        string status,
        string nextAction,
        SimulationVenue[] venues,
        SimulationCandidate[] candidates,
        SimulationOrder[] orders,
        SimulationPosition[] openPositions,
        SimulationPosition[] closedPositions,
        SimulationEvent entry) => new(
            time, title, description, status, nextAction,
            [.. venues], [.. candidates], [.. orders], [.. openPositions], [.. closedPositions], entry);

    private static SimulationVenue Venue(string name, string status, string balance, string available) =>
        new(name, status, balance, available);
