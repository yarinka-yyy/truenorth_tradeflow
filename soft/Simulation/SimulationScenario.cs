internal sealed record SimulationStep(
    string Time,
    string Title,
    string Description,
    string Status,
    string NextAction,
    ImmutableArray<SimulationVenue> Venues,
    ImmutableArray<SimulationCandidate> Candidates,
    ImmutableArray<SimulationOrder> Orders,
    ImmutableArray<SimulationPosition> OpenPositions,
    ImmutableArray<SimulationPosition> ClosedPositions,
    SimulationEvent Event);

internal sealed record SimulationVenue(string Name, string Status, string Balance, string Available);

internal sealed record SimulationCandidate(
    string Market,
    string Venue,
    string Side,
    string EntryType,
    string EntryPrice,
    string TakeProfit,
    string StopLoss);

internal sealed record SimulationOrder(
    string Id,
    string Market,
    string Venue,
    string Side,
    string Price,
    string Status,
    string Filled,
    string Remaining,
    string TakeProfit,
    string StopLoss);

internal sealed record SimulationPosition(
    string Market,
    string Venue,
    string Side,
    string Quantity,
    string EntryPrice,
    string Result,
    string TakeProfit,
    string StopLoss,
    string CloseTime,
    string RealizedResult,
    string CloseReason);

internal enum SimulationNoticeCategory
{
    Opening,
    Closing,
    OrderChange,
    Error,
    Recovery
}

internal sealed record SimulationEvent(
    string Time,
    string Title,
    string Description,
    SimulationNoticeCategory? Category = null,
    bool IsReminder = false)
{
    internal string CategoryLabel => (IsReminder ? "Напоминание · " : string.Empty) + (Category switch
    {
        SimulationNoticeCategory.Opening => "Открытие",
        SimulationNoticeCategory.Closing => "Закрытие",
        SimulationNoticeCategory.OrderChange => "Изменение заявки",
        SimulationNoticeCategory.Error => "Ошибка",
        SimulationNoticeCategory.Recovery => "Восстановление",
        _ => "Событие"
    });
}

internal sealed record SimulationNotification(
    string Time,
    string Category,
    string Title,
    string Message);
